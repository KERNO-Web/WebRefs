export function seed() {
  let id = 1040;
  return RAW.map(([name, product, sum, source, manager, stage, created, inStage, phone, tasks, lostNote]) => {
    const hist = [{ d: -created, who: 'system', text: `Заявка, источник: ${SOURCES[source].name}` }];
    const steps = HISTORY_BY_STAGE[stage];
    steps.forEach((t, i) => {
      const d = -created + Math.round(((created - inStage) * (i + 1)) / (steps.length + 1));
      hist.push({ d, who: manager, text: t });
    });
    if (lostNote) hist.push({ d: -inStage, who: manager, text: lostNote });
    return {
      id: ++id,
      name,
      product,
      sum,
      source,
      manager,
      stage,
      created: -created,
      moved: -inStage,
      phone,
      tasks: tasks.map(([text, due, done], i) => ({ id: `${id}-${i}`, text, due, done })),
      history: hist.sort((a, b) => a.d - b.d),
    };
  });
}

